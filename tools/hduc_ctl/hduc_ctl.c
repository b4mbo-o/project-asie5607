/*
 * hduc_ctl - experimental USB control tool for the SKNET HDUC (ASIE5607)
 *
 * Implements, in Linux/libusb form, the AS11Loader-compatible firmware
 * upload container protocol reverse engineered from the official
 * SKNET_AS11Loader.sys (Ver.1.9.10.20, 2009-11-10) and cross-checked
 * against the ASIE5606-era recfriio/as11loader.c implementation.
 * See README.md in the project root for usage and safety notes.
 *
 * This tool does NOT embed any vendor firmware or cryptographic key
 * material. The --loader-upload command requires the caller to supply
 * an owner-supplied, already-decrypted firmware image.  No extraction key or
 * vendor driver or DLL is distributed here; see NOTICE.md.
 */

