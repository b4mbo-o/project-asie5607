#define LOADER_VID 0x1738
#define LOADER_PID 0x5211
#define HDTVC_VID 0x3275
#define HDTVC_PID 0x7080
#define LOADER_IDX_DEFAULT 0x55d8 /* wValue used by the 2009 HDUC-era AS11Loader */
#define CTRL_TIMEOUT_MS 5000
#define BULK_TIMEOUT_MS 3000
#define ASYNC_MAX_BUFFERS 32
#define ASYNC_MAX_TRANSFER 65536

/* Optional physical USB location filter.  This matters when an HDUC and a
 * U3 are both present in loader mode: both expose the same 1738:5211 ID. */
static int selected_bus = -1;
static int selected_port = -1;

struct fw_chunk {
    uint8_t  bRequest;
    uint32_t offset;
    uint32_t size;
};

/* Sequence reverse engineered from SKNET_AS11Loader.sys FUN_0001078e.
 * Identical container shape to the ASIE5606-era recfriio as11loader.c. */
static const struct fw_chunk LOADER_SEQUENCE[] = {
    { 0xab, 0x0000, 0x0c00 },
    { 0xab, 0x2000, 0x0400 },
    { 0xab, 0x2800, 0x1000 },
    { 0xac, 0x3800, 0x0800 },
};

