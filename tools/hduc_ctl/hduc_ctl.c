static int hduc_heartbeat(libusb_device_handle *h, int send_slow_polls)
{
    unsigned char event[33] = {0};
    unsigned char status[4] = {0};
    int failures = 0;
    int rc = libusb_control_transfer(
        h, LIBUSB_REQUEST_TYPE_VENDOR | LIBUSB_ENDPOINT_IN | LIBUSB_RECIPIENT_DEVICE,
        0x00, 0, 0, event, sizeof(event), 250);
    if (rc != (int)sizeof(event)) failures++;
    if (!send_slow_polls) return failures;

    rc = libusb_control_transfer(
        h, LIBUSB_REQUEST_TYPE_VENDOR | LIBUSB_ENDPOINT_IN | LIBUSB_RECIPIENT_DEVICE,
        0x22, 0x0000, 0, status, 1, 250);
    if (rc != 1) failures++;
    rc = libusb_control_transfer(
        h, LIBUSB_REQUEST_TYPE_VENDOR | LIBUSB_ENDPOINT_IN | LIBUSB_RECIPIENT_DEVICE,
        0x22, 0x0001, 0, status, 1, 250);
    if (rc != 1) failures++;
    rc = libusb_control_transfer(
        h, LIBUSB_REQUEST_TYPE_VENDOR | LIBUSB_ENDPOINT_IN | LIBUSB_RECIPIENT_DEVICE,
        0x02, 0x045a, 0, status, 2, 250);
    if (rc != 2) failures++;
    rc = libusb_control_transfer(
        h, LIBUSB_REQUEST_TYPE_VENDOR | LIBUSB_ENDPOINT_IN | LIBUSB_RECIPIENT_DEVICE,
        0x02, 0x8b20, 0, status, 4, 250);
    if (rc != 4) failures++;
    return failures;
}

static int send_socket_text(int fd, const char *text)
{
    size_t left = strlen(text);
    while (left) {
        ssize_t n = send(fd, text, left, MSG_NOSIGNAL);
        if (n < 0 && errno == EINTR) continue;
        if (n <= 0) return -1;
        text += n;
        left -= (size_t)n;
    }
    return 0;
}

static int read_socket_line(int fd, char *line, size_t capacity)
{
    size_t used = 0;
    while (used + 1 < capacity) {
        char ch;
        ssize_t n = recv(fd, &ch, 1, 0);
        if (n < 0 && errno == EINTR) continue;
        if (n <= 0) return -1;
        if (ch == '\n') {
            line[used] = '\0';
            return 0;
        }
        line[used++] = ch;
    }
    line[capacity - 1] = '\0';
    return -1;
}

static int cmd_hduc_server(libusb_context *ctx, const char *socket_path,
                            uint16_t initial_channel)
{
    enum { SERVER_BUFFERS = 8, SERVER_TRANSFER_SIZE = 8192 };
    if (!socket_path || !*socket_path ||
        strlen(socket_path) >= sizeof(((struct sockaddr_un *)0)->sun_path)) {
        fprintf(stderr, "error: hduc-server requires a shorter --socket PATH\n");
        return 1;
    }
    if (initial_channel < 13 || initial_channel > 62) {
        fprintf(stderr, "error: hduc-server requires --channel 13..62\n");
        return 1;
    }

    libusb_device_handle *h = open_dev(ctx, HDTVC_VID, HDTVC_PID);
    if (!h) return 1;

    int listen_fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (listen_fd < 0) {
        perror("socket");
        libusb_release_interface(h, 0);
        libusb_close(h);
        return 1;
    }

    struct stat st;
    if (lstat(socket_path, &st) == 0) {
        if (!S_ISSOCK(st.st_mode)) {
            fprintf(stderr, "error: refusing to replace non-socket path %s\n", socket_path);
            close(listen_fd);
            libusb_release_interface(h, 0);
            libusb_close(h);
            return 1;
        }
        if (unlink(socket_path) != 0) {
            perror("unlink stale socket");
            close(listen_fd);
            libusb_release_interface(h, 0);
            libusb_close(h);
            return 1;
        }
    } else if (errno != ENOENT) {
        perror("lstat socket path");
        close(listen_fd);
        libusb_release_interface(h, 0);
        libusb_close(h);
        return 1;
    }

    struct sockaddr_un address;
    memset(&address, 0, sizeof(address));
    address.sun_family = AF_UNIX;
    strncpy(address.sun_path, socket_path, sizeof(address.sun_path) - 1);
    if (bind(listen_fd, (struct sockaddr *)&address, sizeof(address)) != 0 ||
        listen(listen_fd, 4) != 0) {
        perror("bind/listen");
        close(listen_fd);
        libusb_release_interface(h, 0);
        libusb_close(h);
        return 1;
    }
    chmod(socket_path, 0660);

    struct async_bulk_ctx stream = {
        .usb_ctx = ctx, .running = 1, .stop_on_output_error = 0,
    };
    struct async_bulk_slot *slots = calloc(SERVER_BUFFERS, sizeof(*slots));
    if (!slots) {
        fprintf(stderr, "error: out of memory\n");
        close(listen_fd);
        unlink(socket_path);
        libusb_release_interface(h, 0);
        libusb_close(h);
        return 1;
    }
    int initialized = 0;
    for (int i = 0; i < SERVER_BUFFERS; i++) {
        slots[i].ctx = &stream;
        slots[i].buffer = malloc(SERVER_TRANSFER_SIZE);
        slots[i].transfer = libusb_alloc_transfer(0);
        if (!slots[i].buffer || !slots[i].transfer) break;
        libusb_fill_bulk_transfer(slots[i].transfer, h, 0x81, slots[i].buffer,
                                  SERVER_TRANSFER_SIZE, async_bulk_callback,
                                  &slots[i], BULK_TIMEOUT_MS);
        int rc = libusb_submit_transfer(slots[i].transfer);
        if (rc != 0) {
            fprintf(stderr, "server bulk submit failed: %s\n", libusb_error_name(rc));
            break;
        }
        stream.active++;
        initialized++;
    }
    if (initialized != SERVER_BUFFERS || hduc_start_stream(h, 1) != 0) {
        stream.running = 0;
        for (int i = 0; i < initialized; i++) libusb_cancel_transfer(slots[i].transfer);
        while (stream.active > 0) {
            struct timeval timeout = { .tv_sec = 0, .tv_usec = 250000 };
            libusb_handle_events_timeout_completed(ctx, &timeout, NULL);
        }
        for (int i = 0; i < SERVER_BUFFERS; i++) {
            if (slots[i].transfer) libusb_free_transfer(slots[i].transfer);
            free(slots[i].buffer);
        }
        free(slots);
        close(listen_fd);
        unlink(socket_path);
        libusb_release_interface(h, 0);
        libusb_close(h);
        return 1;
    }

    signal(SIGINT, server_signal_handler);
    signal(SIGTERM, server_signal_handler);
    signal(SIGPIPE, SIG_IGN);
    server_running = 1;
    async_bulk_running = 1;
    uint64_t now_ms = monotonic_milliseconds();
    uint64_t next_heartbeat = now_ms;
    uint64_t next_slow = now_ms;
    uint64_t next_report = now_ms + 10000;
    unsigned long heartbeats = 0;
    int total_failures = 0;
    int consecutive_failures = 0;
    uint16_t current_channel = initial_channel;
    int client_fd = -1;
    FILE *client_output = NULL;
    uint64_t client_deadline = 0;
    long client_start_bytes = 0;

    printf("HDUC server ready: socket=%s bus=%d port=%d channel=%u; "
           "EP81 remains queued between recordings\n",
           socket_path, selected_bus, selected_port, current_channel);
    fflush(stdout);

    while (server_running && stream.active > 0 && stream.errors <= 5) {
        struct timeval event_timeout = { .tv_sec = 0, .tv_usec = 50000 };
        libusb_handle_events_timeout_completed(ctx, &event_timeout, NULL);
        now_ms = monotonic_milliseconds();

        if (now_ms >= next_heartbeat) {
            int failures = hduc_heartbeat(h, now_ms >= next_slow);
            heartbeats++;
            total_failures += failures;
            consecutive_failures = failures ? consecutive_failures + 1 : 0;
            next_heartbeat = now_ms + 100;
            if (now_ms >= next_slow) next_slow = now_ms + 5000;
        }
        if (now_ms >= next_report) {
            printf("HDUC server: heartbeats=%lu failures=%d bulk_bytes=%ld client=%s\n",
                   heartbeats, total_failures, stream.total_bytes,
                   client_output ? "recording" : "idle");
            fflush(stdout);
            next_report = now_ms + 10000;
        }
        if (consecutive_failures >= 5) {
            fprintf(stderr, "HDUC server: device stopped responding\n");
            break;
        }

        if (client_output && (stream.output_failed ||
                              (client_deadline && now_ms >= client_deadline))) {
            stream.out = NULL;
            fflush(client_output);
            fclose(client_output);
            client_output = NULL;
            shutdown(client_fd, SHUT_RDWR);
            close(client_fd);
            client_fd = -1;
            printf("HDUC server client complete: bytes=%ld output_error=%d\n",
                   stream.total_bytes - client_start_bytes, stream.output_failed);
            stream.output_failed = 0;
            client_deadline = 0;
            fflush(stdout);
        }
        if (client_output) continue;

        struct pollfd descriptor = { .fd = listen_fd, .events = POLLIN };
        int ready = poll(&descriptor, 1, 0);
        if (ready < 0 && errno != EINTR) {
            perror("poll");
            break;
        }
        if (ready <= 0 || !(descriptor.revents & POLLIN)) continue;

        client_fd = accept(listen_fd, NULL, NULL);
        if (client_fd < 0) {
            if (errno != EINTR) perror("accept");
            continue;
        }
        struct timeval command_timeout = { .tv_sec = 5, .tv_usec = 0 };
        struct timeval output_timeout = { .tv_sec = 2, .tv_usec = 0 };
        int output_buffer = 1024 * 1024;
        setsockopt(client_fd, SOL_SOCKET, SO_RCVTIMEO,
                   &command_timeout, sizeof(command_timeout));
        setsockopt(client_fd, SOL_SOCKET, SO_SNDTIMEO,
                   &output_timeout, sizeof(output_timeout));
        setsockopt(client_fd, SOL_SOCKET, SO_SNDBUF,
                   &output_buffer, sizeof(output_buffer));

        char command[128];
        unsigned int requested_channel = 0;
        int seconds = -1;
        char extra = '\0';
        if (read_socket_line(client_fd, command, sizeof(command)) != 0 ||
            sscanf(command, "RECORD %u %d %c", &requested_channel, &seconds, &extra) != 2 ||
            requested_channel < 13 || requested_channel > 62 || seconds < 0) {
            send_socket_text(client_fd, "ERR expected RECORD channel(13..62) seconds(>=0)\n");
            close(client_fd);
            client_fd = -1;
            continue;
        }

        if (requested_channel != current_channel) {
            printf("HDUC server retune: ch%u -> ch%u\n",
                   current_channel, requested_channel);
            fflush(stdout);
            if (hduc_tune_on_handle(h, (uint16_t)requested_channel, 0) != 0) {
                send_socket_text(client_fd, "ERR tune failed\n");
                close(client_fd);
                client_fd = -1;
                continue;
            }
            uint64_t settle_end = monotonic_milliseconds() + 1000;
            while (server_running && monotonic_milliseconds() < settle_end) {
                struct timeval timeout = { .tv_sec = 0, .tv_usec = 50000 };
                libusb_handle_events_timeout_completed(ctx, &timeout, NULL);
                uint64_t settle_now = monotonic_milliseconds();
                if (settle_now >= next_heartbeat) {
                    int failures = hduc_heartbeat(h, settle_now >= next_slow);
                    heartbeats++;
                    total_failures += failures;
                    next_heartbeat = settle_now + 100;
                    if (settle_now >= next_slow) next_slow = settle_now + 5000;
                }
            }
            /* Frequency programming stops EP81.  The restart succeeds only
             * after hduc_tune_on_handle has restored the x64 PID-filter state;
             * issuing 0x06 without that state yields a short residual burst
             * and an idle endpoint.  Keep the existing URBs queued, settle,
             * then use the same start/post-start requests as Windows. */
            if (!server_running || hduc_start_stream(h, 1) != 0) {
                send_socket_text(client_fd, "ERR stream restart failed\n");
                close(client_fd);
                client_fd = -1;
                continue;
            }
            current_channel = (uint16_t)requested_channel;
        }

        if (send_socket_text(client_fd, "OK\n") != 0) {
            close(client_fd);
            client_fd = -1;
            continue;
        }
        int output_fd = dup(client_fd);
        client_output = output_fd >= 0 ? fdopen(output_fd, "wb") : NULL;
        if (!client_output) {
            if (output_fd >= 0) close(output_fd);
            close(client_fd);
            client_fd = -1;
            continue;
        }
        setvbuf(client_output, NULL, _IOFBF, 64 * 1024);
        stream.output_failed = 0;
        stream.out = client_output;
        client_start_bytes = stream.total_bytes;
        client_deadline = seconds ? monotonic_milliseconds() + (uint64_t)seconds * 1000u : 0;
        if (seconds)
            printf("HDUC server client: channel=%u seconds=%d\n",
                   requested_channel, seconds);
        else
            printf("HDUC server client: channel=%u seconds=until-disconnect\n",
                   requested_channel);
        fflush(stdout);
    }

    stream.out = NULL;
    if (client_output) {
        fflush(client_output);
        fclose(client_output);
    }
    if (client_fd >= 0) close(client_fd);
    stream.running = 0;
    for (int i = 0; i < initialized; i++) libusb_cancel_transfer(slots[i].transfer);
    while (stream.active > 0) {
        struct timeval timeout = { .tv_sec = 0, .tv_usec = 250000 };
        libusb_handle_events_timeout_completed(ctx, &timeout, NULL);
    }
    for (int i = 0; i < SERVER_BUFFERS; i++) {
        if (slots[i].transfer) libusb_free_transfer(slots[i].transfer);
        free(slots[i].buffer);
    }
    free(slots);
    close(listen_fd);
    unlink(socket_path);
    libusb_release_interface(h, 0);
    libusb_close(h);
    printf("HDUC server stopped: heartbeats=%lu failures=%d bulk_bytes=%ld errors=%d\n",
           heartbeats, total_failures, stream.total_bytes, stream.errors);
    return (consecutive_failures >= 5 || stream.errors > 5) ? 1 : 0;
}

static int run_hduc_keepalive_on_handle(libusb_device_handle *h, int seconds,
                                         int interval_ms)
{
    signal(SIGINT, keepalive_signal_handler);
    signal(SIGTERM, keepalive_signal_handler);
    keepalive_running = 1;
    time_t started = time(NULL);
    time_t deadline = seconds ? started + seconds : 0;
    time_t next_slow = started;
    time_t next_report = started + 10;
    unsigned long heartbeats = 0;
    int total_failures = 0;
    int consecutive_failures = 0;
    printf("HDUC keepalive active: interval=%dms duration=%s\n",
           interval_ms, seconds ? "bounded" : "until signal");
    fflush(stdout);

    while (keepalive_running && (!deadline || time(NULL) < deadline)) {
        time_t now = time(NULL);
        int failures = hduc_heartbeat(h, now >= next_slow);
        heartbeats++;
        total_failures += failures;
        consecutive_failures = failures ? consecutive_failures + 1 : 0;
        if (now >= next_slow) next_slow = now + 5;
        if (now >= next_report) {
            printf("HDUC keepalive: elapsed=%lds heartbeats=%lu failures=%d\n",
                   (long)(now - started), heartbeats, total_failures);
            fflush(stdout);
            next_report = now + 10;
        }
        if (consecutive_failures >= 5) {
            fprintf(stderr, "HDUC keepalive: device stopped responding\n");
            break;
        }
        sleep_milliseconds((double)interval_ms);
    }
    printf("HDUC keepalive stopped: elapsed=%lds heartbeats=%lu failures=%d\n",
           (long)(time(NULL) - started), heartbeats, total_failures);
    return consecutive_failures >= 5 ? 1 : 0;
}

static int cmd_hduc_keepalive(libusb_context *ctx, int seconds, int interval_ms)
{
    if (seconds < 0 || interval_ms < 20) {
        fprintf(stderr, "error: hduc-keepalive requires seconds >= 0 and interval >= 20 ms\n");
        return 1;
    }
    libusb_device_handle *h = open_dev(ctx, HDTVC_VID, HDTVC_PID);
    if (!h) return 1;
    int rc = run_hduc_keepalive_on_handle(h, seconds, interval_ms);
    libusb_release_interface(h, 0);
    libusb_close(h);
    return rc;
}

static int cmd_u3_monitor(libusb_context *ctx, uint16_t vid, uint16_t pid,
                          int seconds, int interval_ms)
{
    if (seconds < 1 || interval_ms < 1) {
        fprintf(stderr, "error: invalid u3-monitor arguments\n");
        return 1;
    }
    libusb_device_handle *h = open_dev(ctx, vid, pid);
    if (!h) return 1;
    time_t end = time(NULL) + seconds;
    int failures = 0, sample = 0;
    printf("Read-only U3 status monitor for %d second(s), every %d ms:\n", seconds, interval_ms);
    while (time(NULL) < end) {
        unsigned char tuner_state[4] = {0};
        unsigned char stream_state[2] = {0};
        int a = u3_status_read(h, 0x8b30, tuner_state, sizeof(tuner_state));
        int b = u3_status_read(h, 0xc332, stream_state, sizeof(stream_state));
        printf("  #%d  8b30=", ++sample);
        if (a == 4) printf("%02x %02x %02x %02x", tuner_state[0], tuner_state[1], tuner_state[2], tuner_state[3]);
        else { printf("<%d %s>", a, a < 0 ? libusb_error_name(a) : "short"); failures++; }
        printf("  c332=");
        if (b == 2) printf("%02x %02x", stream_state[0], stream_state[1]);
        else { printf("<%d %s>", b, b < 0 ? libusb_error_name(b) : "short"); failures++; }
        printf("\n");
        sleep_milliseconds((double)interval_ms);
    }
    libusb_release_interface(h, 0);
    libusb_close(h);
    return failures ? 1 : 0;
}

int main(int argc, char **argv)
{
    if (argc < 2) { print_usage(argv[0]); return 1; }

    uint16_t vid = LOADER_VID, pid = LOADER_PID;
    uint16_t idx = LOADER_IDX_DEFAULT;
    int dir_in = -1;
    uint8_t req = 0;
    uint16_t val = 0, wlen = 0;
    const char *hexdata = NULL;
    const char *fwpath = NULL;
    const char *cmd = argv[1];
    uint16_t channel = 0;
    uint8_t ep = 0;
    int seconds = 5;
    const char *outpath = NULL;
    int buffers = 8;
    int bulk_size = 8192;
    int start_req = 0;
    int hduc_post_start = 0;
    int hold_after = -1;
    int keep_going = 0;
    int proxy_retries = 0;
    int interval_ms = 1000;
    const char *seqpath = NULL;
    const char *ready_file = NULL;
    const char *socket_path = NULL;
    int dry_run = 0, quiet = 0;
    double scale = 1.0;

    for (int i = 2; i < argc; i++) {
        if (!strcmp(argv[i], "--vid") && i + 1 < argc) vid = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--pid") && i + 1 < argc) pid = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--bus") && i + 1 < argc) selected_bus = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--port") && i + 1 < argc) selected_port = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--idx") && i + 1 < argc) idx = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--dir") && i + 1 < argc) dir_in = !strcmp(argv[++i], "in");
        else if (!strcmp(argv[i], "--req") && i + 1 < argc) req = (uint8_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--val") && i + 1 < argc) val = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--len") && i + 1 < argc) wlen = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--data") && i + 1 < argc) hexdata = argv[++i];
        else if (!strcmp(argv[i], "--channel") && i + 1 < argc) channel = (uint16_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--ep") && i + 1 < argc) ep = (uint8_t)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--seconds") && i + 1 < argc) seconds = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--buffers") && i + 1 < argc) buffers = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--size") && i + 1 < argc) bulk_size = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--start") && i + 1 < argc) start_req = (int)strtol(argv[++i], NULL, 0);
        else if (!strcmp(argv[i], "--hduc-post-start")) hduc_post_start = 1;
        else if (!strcmp(argv[i], "--hold-after") && i + 1 < argc) hold_after = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--ready-file") && i + 1 < argc) ready_file = argv[++i];
        else if (!strcmp(argv[i], "--socket") && i + 1 < argc) socket_path = argv[++i];
        else if (!strcmp(argv[i], "--keep-going")) keep_going = 1;
        else if (!strcmp(argv[i], "--proxy-retries") && i + 1 < argc) proxy_retries = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--interval-ms") && i + 1 < argc) interval_ms = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--out") && i + 1 < argc) outpath = argv[++i];
        else if (!strcmp(argv[i], "--file") && i + 1 < argc) seqpath = argv[++i];
        else if (!strcmp(argv[i], "--dry-run")) dry_run = 1;
        else if (!strcmp(argv[i], "--quiet")) quiet = 1;
        else if (!strcmp(argv[i], "--scale") && i + 1 < argc) scale = strtod(argv[++i], NULL);
        else if (!fwpath && argv[i][0] != '-') fwpath = argv[i];
    }

    libusb_context *ctx = NULL;
    if (libusb_init(&ctx) != 0) {
        fprintf(stderr, "libusb_init failed\n");
        return 1;
    }

    int rc;
    if (!strcmp(cmd, "info")) {
        rc = cmd_info(ctx, vid, pid);
    } else if (!strcmp(cmd, "loader-upload")) {
        if (!fwpath) { print_usage(argv[0]); rc = 1; }
        else rc = cmd_loader_upload(ctx, fwpath, idx);
    } else if (!strcmp(cmd, "vendor-ctl")) {
        if (dir_in == -1) { fprintf(stderr, "error: --dir in|out required\n"); rc = 1; }
        else rc = cmd_vendor_ctl(ctx, vid, pid, dir_in, req, val, idx, wlen, hexdata);
    } else if (!strcmp(cmd, "replay-control")) {
        if (!seqpath) { fprintf(stderr, "error: --file SEQUENCE required\n"); rc = 1; }
        else rc = cmd_replay_control(ctx, vid, pid, seqpath, dry_run, scale, quiet,
                                     ep, seconds, buffers, bulk_size, outpath, keep_going,
                                     proxy_retries);
    } else if (!strcmp(cmd, "reset")) {
        rc = cmd_reset(ctx, vid, pid);
    } else if (!strcmp(cmd, "tune")) {
        if (channel == 0) { fprintf(stderr, "error: --channel N required\n"); rc = 1; }
        else rc = cmd_tune(ctx, channel, dry_run);
    } else if (!strcmp(cmd, "dump-bulk")) {
        if (ep == 0) { fprintf(stderr, "error: --ep 0x81|0x82 required\n"); rc = 1; }
        else rc = cmd_dump_bulk(ctx, ep, seconds, outpath);
    } else if (!strcmp(cmd, "async-bulk")) {
        if (ep == 0) { fprintf(stderr, "error: --ep 0x81|0x82 required\n"); rc = 1; }
        else rc = cmd_async_bulk(ctx, vid, pid, ep, seconds, buffers, bulk_size, outpath,
                                 start_req, hduc_post_start, hold_after, ready_file);
    } else if (!strcmp(cmd, "u3-monitor")) {
        rc = cmd_u3_monitor(ctx, vid, pid, seconds, interval_ms);
    } else if (!strcmp(cmd, "hduc-keepalive")) {
        rc = cmd_hduc_keepalive(ctx, seconds, interval_ms);
    } else if (!strcmp(cmd, "hduc-server")) {
        rc = cmd_hduc_server(ctx, socket_path, channel);
    } else {
        print_usage(argv[0]);
        rc = 1;
    }

    libusb_exit(ctx);
    return rc;
}
